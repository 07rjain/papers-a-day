"use client";

import { useState } from "react";
import { VizNote } from "@/components/viz/shell";

export function PromptBuilder() {
  const [examples, setExamples] = useState("How are you? → Comment allez-vous?\nGood morning. → Bonjour.");
  const [query, setQuery] = useState("Where is the library?");
  const prompt = `${examples.trim()}\n${query.trim()} →`;
  const lines = examples.split("\n").map((line) => line.trim()).filter(Boolean).length;
  return (
    <div>
      <VizNote>
        Toy few-shot prompt builder. Nothing here is generated by GPT-3. The point is only how many
        worked examples sit in the context before the query.
      </VizNote>
      <div className="viz-controls">
        <label>
          Worked examples, one per line
          <textarea value={examples} onChange={(event) => setExamples(event.target.value)} rows={4} aria-label="Worked examples" />
        </label>
        <label>
          Your English sentence
          <input type="text" value={query} onChange={(event) => setQuery(event.target.value)} aria-label="Sentence to continue" />
        </label>
      </div>
      <pre className="prompt-preview">{prompt}</pre>
      <p className="viz-note">
        {lines === 0 ? "Zero-shot: instruction-like text only." : lines === 1 ? "One-shot: a single demo." : `Few-shot: ${lines} demos.`} Weights stay frozen; only the prompt text changed.
      </p>
    </div>
  );
}
